def test_run_market_writes_file_only_with_enough_postings(tmp_path):
    db = MemoryDB()
    rows = [{**v.to_row(), "region": "UK", "role_family": "legal intern", "query": "legal intern"}
            for v in _vacs(25)]
    rows += [{**v.to_row(), "url": v.url + "-p", "region": "UK", "role_family": "intern", "query": "intern"}
             for v in _vacs(5)]
    db.upsert_vacancies(rows)
    res = run_market(db, FakeLLM(), ["law", "other"], ["UK", "EU"], 30, "2026-01-02", tmp_path)
    assert (tmp_path / "law.md").exists() and not (tmp_path / "other.md").exists()
    assert res["written"] == [tmp_path / "law.md"]
    assert "excel 100%" in (tmp_path / "law.md").read_text()
    saved = db.skill_demand("law", "UK")
    assert {r["skill"] for r in saved} == {"excel", "sql"} and saved[0]["total_postings"] == 25
    assert db.skill_demand("other", "UK")  # data is stored for small directions too

    db2 = MemoryDB()
    db2.upsert_vacancies(rows)
    tmp2 = tmp_path / "dry"
    run_market(db2, FakeLLM(), ["law"], ["UK"], 30, "2026-01-02", tmp2, dry_run=True)
    assert not tmp2.exists() and db2.skill_demand("law", "UK") == []


def _law_db(n):
    db = MemoryDB()
    db.upsert_vacancies([{**v.to_row(), "region": "UK", "role_family": "legal intern", "query": "legal intern"}
                         for v in _vacs(n)])
    return db


def test_run_market_half_batches_failed_skips_region(tmp_path, capsys):
    db = _law_db(100)  # 4 batches of 25
    llm = FakeLLM(fail_calls={2, 4})
    res = run_market(db, llm, ["law"], ["UK"], 30, "2026-01-02", tmp_path)
    assert len(llm.calls) == 4
    assert db.skill_demand("law", "UK") == [] and res["written"] == [] and not (tmp_path / "law.md").exists()
    assert "coverage 50%" in capsys.readouterr().out
    # the share is counted from the covered postings
    skills, covered = extract_skills(FakeLLM(fail_calls={2, 4}), [{"id": str(i), "title": "x"} for i in range(100)])
    assert len(covered) == 50 and aggregate(skills, len(covered))[0]["share"] == 1.0


def test_run_market_all_batches_failed_keeps_existing_file(tmp_path):
    db = _law_db(50)
    path = tmp_path / "law.md"
    path.write_text("old good content\n", encoding="utf-8")
    res = run_market(db, FakeLLM(fail_calls={1, 2}), ["law"], ["UK"], 30, "2026-01-02", tmp_path)
    assert res["written"] == [] and path.read_text(encoding="utf-8") == "old good content\n"
    assert db.skill_demand("law", "UK") == []
    run_market(db, FakeLLM(fail_calls={1, 2}), ["law"], ["UK"], 30, "2026-01-02", tmp_path / "fresh")
    assert not (tmp_path / "fresh").exists()


def test_run_market_one_of_ten_batches_failed_keeps_region(tmp_path):
    db = _law_db(250)  # 10 batches of 25
    res = run_market(db, FakeLLM(fail_calls={3}), ["law"], ["UK"], 30, "2026-01-02", tmp_path)
    saved = db.skill_demand("law", "UK")
    assert saved and all(r["total_postings"] == 225 and r["postings"] == 225 for r in saved)
    assert res["written"] == [tmp_path / "law.md"]
    assert res["by_program"]["law"]["UK"][0] == 225
    assert "UK: 225 postings" in (tmp_path / "law.md").read_text() and "excel 100%" in (tmp_path / "law.md").read_text()
