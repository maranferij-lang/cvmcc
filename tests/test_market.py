def test_normalise_skill():
    assert normalise_skill("  MS Excel ") == "excel"
    assert normalise_skill("PostgreSQL") == "sql"
    assert normalise_skill("Power-BI") == "power bi"
    assert normalise_skill("English  C1") == "english"
    assert normalise_skill("C++.") == "c++"
    assert normalise_skill("x" * 41) == ""
    assert normalise_skill("  ..  ") == ""


def test_aggregate_shares_and_top():
    by_id = {str(i): {"sql", "excel"} if i < 5 else {"python"} for i in range(10)}
    by_id["x"] = {"rare"}
    rows = aggregate(by_id, 100, min_share=0.03)
    assert [r["skill"] for r in rows] == ["excel", "python", "sql"]  # 5 levels: alphabetical; rare = 1% < 3%
    assert rows[0] == {"skill": "excel", "postings": 5, "total_postings": 100, "share": 0.05}
    many = {str(i): {f"s{j}" for j in range(30)} for i in range(10)}
    assert len(aggregate(many, 10, top=20)) == 20


class FakeLLM:
    def __init__(self, fail_call=None, fail_calls=()):
        self.calls, self.fail_call, self.fail_calls = [], fail_call, set(fail_calls)

    def ask(self, *, system, content, output_model, effort):
        self.calls.append(content[0]["text"])
        if self.fail_call == len(self.calls) or len(self.calls) in self.fail_calls:
            raise LLMError("boom")
        ids = [ln[3:] for ln in content[0]["text"].splitlines() if ln.startswith("id=")]
        return output_model(items=[PostingSkills(id=i, skills=["MS Excel", "SQL"]) for i in ids])


def test_extract_skills_batches_and_survives_error():
    postings = [{"id": str(i), "title": "Analyst", "company": "Acme", "snippet": "sql"} for i in range(60)]
    llm = FakeLLM(fail_call=2)
    out, covered = extract_skills(llm, postings, batch=25)
    assert len(llm.calls) == 3
    assert len(out) == 35  # 25 + 10, the middle batch skipped
    assert out["0"] == {"excel", "sql"}
    assert covered == {str(i) for i in range(60)} - {str(i) for i in range(25, 50)}


def test_extract_skills_empty_posting_is_covered():
    class EmptyLLM:
        def ask(self, *, system, content, output_model, effort):
            return output_model(items=[])

    out, covered = extract_skills(EmptyLLM(), [{"id": "a", "title": "t"}, {"id": "b", "title": "t"}])
    assert out == {} and covered == {"a", "b"}


def test_render_market_cap_and_content():
    rows = [{"skill": f"skill{i}", "postings": 50 - i, "total_postings": 100, "share": 0.5 - i / 100}
            for i in range(20)]
    text = render_market("law", {"UK": (100, rows), "EU": (0, [])}, 30, "2026-01-02")
    assert text.startswith("<!-- generated by scripts/learn_market.py on 2026-01-02 -->")
    assert "## What postings ask for right now (last 30 days)" in text
    assert "UK: 100 postings for legal intern" in text and "skill0 50%" in text
    assert "EU:" not in text
    huge = {f"R{i}": (100, rows) for i in range(30)}
    assert len(render_market("law", huge, 30, "2026-01-02")) <= market.RENDER_MAX_CHARS


def _vacs(n):
    return [Vacancy(url=f"https://example.com/{i}", title=f"Job {i}", company="Acme", location="Kyiv",
                    source="DOU", posted_at="2026-01-01", salary=None, snippet="sql", remote=False)
            for i in range(n)]


def test_run_snapshot_writes_rows_and_dry_run():
    db = MemoryDB()
    calls = []

    def search(q):
        calls.append(q)
        return SimpleNamespace(vacancies=_vacs(3), sources_ok=["DOU"], sources_failed=["Jooble"], deep_links=[])

    summary = run_snapshot(db, search, ["law"], ["UK"], sleep=0)
    assert len(calls) == len(market.ROLE_QUERIES["law"])
    assert calls[0].level == "Internship" and calls[0].region == "UK"
    assert summary == [{"program": "law", "region": "UK", "fetched": 12, "upserted": 12, "failed": 4}]
    row = db.vacancies[("https://example.com/0", market.ROLE_QUERIES["law"][-1], "UK")]  # MemoryDB key: (url, role_family, region)
    assert row["region"] == "UK" and row["role_family"] == market.ROLE_QUERIES["law"][-1]

    db2 = MemoryDB()
    run_snapshot(db2, search, ["law"], ["UK"], sleep=0, dry_run=True)
    assert db2.vacancies == {}


